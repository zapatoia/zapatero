def glyph(ch):
    """Devuelve 9 filas (2 para tilde + 7)."""
    ch = ch.upper()
    if ch in _ACC:
        base = _G[_ACC[ch]]
        top = _ACC_ROWS.get(ch, ["...#.", "..#.."])
        return top + base
    g = _G.get(ch, _G["?"])
    return [".....", "....."] + g


def text_bitmap(text, spacing=1, line_gap=1):
    lines = text.upper().split("\n")
    rows_all = []
    width = max(len(l) for l in lines) * (5 + spacing) - spacing
    for li, line in enumerate(lines):
        rows = ["" for _ in range(9)]
        for i, ch in enumerate(line):
            g = glyph(ch)
            for r in range(9):
                rows[r] += g[r] + ("." * spacing if i < len(line) - 1 else "")
        # centrar cada línea
        pad = width - len(rows[0])
        rows = ["." * (pad // 2) + r + "." * (pad - pad // 2) for r in rows]
        if li > 0:
            rows_all += ["." * width] * line_gap
        rows_all += rows
    return rows_all


def bitmap_array(rows):
    return np.array([[c == "#" for c in r] for r in rows], bool)


def trim_rows(rows):
    """Quita filas vacías arriba/abajo (para vóxeles)."""
    while rows and "#" not in rows[0]:
        rows = rows[1:]
    while rows and "#" not in rows[-1]:
        rows = rows[:-1]
    return rows
